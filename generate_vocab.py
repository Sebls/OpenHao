#!/usr/bin/env python3
"""
Chinese Vocabulary Typst Generator.

This script reads JSON vocabulary files from `data/` (or a specified file),
generates Typst documents with individual and grouped flashcards,
and compiles them directly into a designated `vocabulary/` directory.

Usage:
    python3 generate_vocab.py                     # Process all JSON files in data/
    python3 generate_vocab.py data/saludos.json   # Process a specific JSON file
    python3 generate_vocab.py --compile           # Generate Typst and automatically compile to PDF
"""

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


def escape_typst_string(s: str) -> str:
    """Escape quotes and backslashes for Typst string literals."""
    if not s:
        return ""
    return s.replace('\\', '\\\\').replace('"', '\\"')


def generate_typst_content(title: str, subtitle: str, json_relative_path: str, items: list) -> str:
    """Generate a clean, standalone Typst document for a vocabulary set."""
    lines = [
        '// Auto-generated by generate_vocab.py',
        '#import "../templates/card.typ": card-doc, vocab-card, vocab-card-compact',
        '',
        f'#show: card-doc.with(',
        f'  title: "{escape_typst_string(title)}",',
        f'  subtitle: "{escape_typst_string(subtitle)}",',
        '  author: "Personal Language System"',
        ')',
        '',
        f'== Study Cards / 学习卡片 ({len(items)} items)',
        ''
    ]

    for item in items:
        hanzi = escape_typst_string(item.get("hanzi", ""))
        phonetic = escape_typst_string(item.get("phonetic", ""))
        written = escape_typst_string(item.get("written", ""))
        definition = escape_typst_string(item.get("definition", ""))
        composition_note = escape_typst_string(item.get("composition_note", ""))
        en = escape_typst_string(item.get("en", ""))
        es = escape_typst_string(item.get("es", ""))
        fr = escape_typst_string(item.get("fr", ""))
        category = escape_typst_string(item.get("category", "Vocabulary"))
        note = escape_typst_string(item.get("note", ""))

        tags_str = ", ".join(f'"{escape_typst_string(t)}"' for t in item.get("tags", []))

        # Breakdown array
        breakdown_entries = []
        for b in item.get("breakdown", []):
            b_char = escape_typst_string(b.get("char", ""))
            b_pinyin = escape_typst_string(b.get("pinyin", ""))
            b_meaning = escape_typst_string(b.get("meaning", ""))
            b_rad = escape_typst_string(b.get("radical", ""))
            entry = f'(char: "{b_char}", pinyin: "{b_pinyin}", meaning: "{b_meaning}", radical: "{b_rad}")'
            breakdown_entries.append(entry)
        breakdown_str = f"({', '.join(breakdown_entries)})" if breakdown_entries else "()"

        # Example dictionary
        example_obj = item.get("example")
        if example_obj:
            ex_zh = escape_typst_string(example_obj.get("zh", ""))
            ex_pinyin = escape_typst_string(example_obj.get("pinyin", ""))
            ex_en = escape_typst_string(example_obj.get("en", ""))
            ex_es = escape_typst_string(example_obj.get("es", ""))
            example_str = f'(zh: "{ex_zh}", pinyin: "{ex_pinyin}", en: "{ex_en}", es: "{ex_es}")'
        else:
            example_str = "none"

        lines.append('#vocab-card(')
        lines.append(f'  hanzi: "{hanzi}",')
        lines.append(f'  pinyin-phonetic: "{phonetic}",')
        lines.append(f'  pinyin-written: "{written}",')
        if definition:
            lines.append(f'  definition: "{definition}",')
        if breakdown_entries:
            lines.append(f'  breakdown: {breakdown_str},')
        if composition_note:
            lines.append(f'  composition-note: "{composition_note}",')
        if en:
            lines.append(f'  en: "{en}",')
        if es:
            lines.append(f'  es: "{es}",')
        if fr:
            lines.append(f'  fr: "{fr}",')
        if example_obj:
            lines.append(f'  example: {example_str},')
        if tags_str:
            lines.append(f'  tags: ({tags_str}),')
        if note:
            lines.append(f'  note: "{note}",')
        lines.append(f'  category: "{category}"')
        lines.append(')')
        lines.append('')

    # Printable flashcards page
    lines.append('#pagebreak()')
    lines.append('== Printable Flashcards / Cutout Grid View (2-Column)')
    lines.append('#v(8pt)')
    lines.append('#grid(')
    lines.append('  columns: (1fr, 1fr),')
    lines.append('  column-gutter: 14pt,')
    lines.append('  row-gutter: 14pt,')

    for item in items:
        hanzi = escape_typst_string(item.get("hanzi", ""))
        phonetic = escape_typst_string(item.get("phonetic", ""))
        written = escape_typst_string(item.get("written", ""))
        en = escape_typst_string(item.get("en", ""))
        es = escape_typst_string(item.get("es", ""))
        fr = escape_typst_string(item.get("fr", ""))
        category = escape_typst_string(item.get("category", "Vocabulary"))

        breakdown_entries = []
        for b in item.get("breakdown", []):
            b_char = escape_typst_string(b.get("char", ""))
            b_pinyin = escape_typst_string(b.get("pinyin", ""))
            b_meaning = escape_typst_string(b.get("meaning", ""))
            breakdown_entries.append(f'(char: "{b_char}", pinyin: "{b_pinyin}", meaning: "{b_meaning}")')
        breakdown_str = f"({', '.join(breakdown_entries)})" if breakdown_entries else "()"

        lines.append('  vocab-card-compact(')
        lines.append(f'    hanzi: "{hanzi}",')
        lines.append(f'    pinyin-phonetic: "{phonetic}",')
        lines.append(f'    pinyin-written: "{written}",')
        lines.append(f'    en: "{en}",')
        lines.append(f'    es: "{es}",')
        lines.append(f'    fr: "{fr}",')
        lines.append(f'    category: "{category}",')
        lines.append(f'    breakdown: {breakdown_str}')
        lines.append('  ),')

    lines.append(')')
    lines.append('')

    return "\n".join(lines)


def process_file(json_file_path: Path, output_dir: Path, compile_pdf: bool = True) -> Path:
    """Read a JSON vocabulary file and generate the corresponding Typst document and PDF."""
    print(f"📖 Reading {json_file_path} ...")
    with open(json_file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, list):
        raise ValueError(f"Expected JSON array in {json_file_path}, got {type(data)}")

    stem = json_file_path.stem
    title = stem.replace("_", " ").replace("-", " ").title()
    subtitle = f"Vocabulary Module · {len(data)} Expressions"

    typst_code = generate_typst_content(
        title=f"Chinese Vocabulary: {title}",
        subtitle=subtitle,
        json_relative_path=str(json_file_path),
        items=data
    )

    output_dir.mkdir(parents=True, exist_ok=True)
    typst_output_path = output_dir / f"{stem}.typ"

    with open(typst_output_path, "w", encoding="utf-8") as f:
        f.write(typst_code)
    print(f"✅ Generated Typst file: {typst_output_path}")

    if compile_pdf:
        pdf_output_path = output_dir / f"{stem}.pdf"
        print(f"⚙️ Compiling {typst_output_path.name} to {pdf_output_path.name} ...")
        cmd = ["typst", "compile", "--root", str(output_dir.parent), str(typst_output_path), str(pdf_output_path)]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode == 0:
            print(f"🎉 PDF successfully compiled: {pdf_output_path}")
        else:
            print(f"❌ Typst compilation error:\n{res.stderr}", file=sys.stderr)

    return typst_output_path


def main():
    parser = argparse.ArgumentParser(description="Generate Typst vocabulary cards from JSON files.")
    parser.add_argument("input_files", nargs="*", help="Optional specific JSON files to process.")
    parser.add_argument("--output-dir", "-o", default="vocabulary", help="Output directory for generated files (default: vocabulary).")
    parser.add_argument("--no-compile", action="store_true", help="Only generate .typ files without compiling to PDF.")

    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent
    output_dir = project_root / args.output_dir
    data_dir = project_root / "data"

    if args.input_files:
        files_to_process = [Path(f).resolve() for f in args.input_files]
    else:
        files_to_process = list(data_dir.glob("*.json"))

    if not files_to_process:
        print(f"⚠️ No JSON files found in {data_dir}. Place your vocabulary JSON files in data/.")
        sys.exit(0)

    print(f"🚀 Found {len(files_to_process)} vocabulary file(s) to process into '{args.output_dir}/'")
    for json_file in files_to_process:
        process_file(json_file, output_dir, compile_pdf=not args.no_compile)

    print(f"\n✨ All done! Generated files are located in: {output_dir}")


if __name__ == "__main__":
    main()
